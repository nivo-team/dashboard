/**
 * 全屏：**默认不跳**。数据在对话里给全 —— 这正是「全屏可以做完所有业务」的起点。
 *
 * 跳转退化成"建议卡"（`navigate_to` 在全屏不真跳）：由用户点卡片决定，AI 不等待、
 * 也不该因为用户没点就反复提议。
 */
function spherePlaybook(): string[] {
  return [
    '# 数据与页面交互决策（当前在**全屏对话页**：默认不跳转，把数据直接放在这里）',
    '1. 【单模块 / 单列表查询（主路径：在对话里呈现）】：',
    '   - 用户问某个模块的数据、列表、明细时，**就在当前对话里给出来**：先 `list_navigation` 定位到模块、`search_api` 找到接口，再 `call_read_api` 取数，用 Markdown 表格或摘要呈现（数据长就分页 / 加筛选条件取精确的一批）。',
    '   - **不要**为了"看得更清楚"就把用户送走 —— 全屏本来就是为了让用户在同一处把事看完。',
    '2. 【需要页面时（次路径：给建议卡）】：',
    '   - 只有下列情况才调用 `navigate_to`：用户**明确表示**想去页面看（「打开页面」「带我去表格示例」「去详情页」）、或这个操作只有页面上才能完成（新建/编辑等表单操作）。',
    '   - 全屏里的 `navigate_to` **不会真的跳转**：它会渲染成一张**建议卡**，由用户自己点。所以调用它之后要**继续把能给的数据给出来**（不要只丢一张卡就结束），并说明「想看完整页面可以点上面的卡片」。',
    '   - 建议卡**与模式无关**（它在全屏里不是"确认"、而是去看页面的入口）：无论询问还是自动模式，全屏都由用户点卡片决定，**不要**把它当成"你已经跳过去了"。',
    '   - **同一轮最多提议一张卡**、同一个目标不要重复提议；用户没点就当他暂时不想去，不要追问。',
    '3. 【多模块 / 跨应用综合统计】：与面板一致 —— `search_api` + `call_read_api` 取数，用 Markdown 表格汇总。',
  ]
}

function panelWorkingRules(): string[] {
  return [
    '- **要查数据前先 get_page_context**：它会给出当前页面用到的接口与**参数明细**（参数名 / 位置 / 是否必填）。有它就别去 search_api 里大海捞针，更**不要凭印象猜参数名** —— 猜错会被后端直接拒掉（例如把 `id` 写成 `uid`）。',
    '- **用户要求在当前页面搜索、过滤、排序或翻页时**：直接调用 `update_search_params` 更新搜索参数（例如设置 kw 搜索关键词、field/order 排序、page 页码或各项筛选字段；清空筛选时将对应参数设为 null）。该操作属于只读视图筛选，直接更新生效，无需等待确认。涉及相对时间（「最近三天」）先用 `get_current_time` 换算成时间戳再传。',
    '- **单条数据新建 / 编辑时**：若用户仅要求创建或修改**单条**数据，且当前页面表单尚未打开，先调用 `open_form` 唤起表单（可直接附带 `values`）；表单打开后如需修改可调用 `fill_form`；用户核对无误后，用 `submit_form` 提交。**注意：批量新建不要走这条路** —— 见下面的编排规约。',
    '- **批量 / 多步骤操作（2 项及以上，含批量删除、批量改状态、批量新建、生成测试数据）**：**严禁直接并发调用多个写接口、严禁循环调用 open_form、严禁循环逐条调用单条接口**。**必须**用 `manage_tasks` 一次给出整组步骤（每步 `action: { tool, input }`），客户端会顺序执行完、一次确认、把结果整批回传，你再据此总结。**这在后端只有单条接口时是唯一的做法**。',
    '- **删除类动作（单个 / 批量）没有表单可走**：先用 `call_read_api` 或 `get_page_data` 查出要删的对象、拿到它的 `id`；**批量删除**时：若接口清单里有批量端点（如 `POST /xxx/batch-delete` + `body: { ids }`）就用它；**若没有（如工单模块只有 `DELETE /xxx/{id}`）就用 `manage_tasks` 把 N 次单条删除编排成一份计划**，不要循环调用。系统会弹审批卡并标明不可撤销，用户拒绝就停下、不要重试；删完页面会自己刷新。',
    '- **跨多个页面的数据聚合 / 综合统计**：不要逐页 `navigate_to` 跳过去。用 `search_pages` 按功能检索出相关页面（返回里带各页的接口清单），再用 `get_page_context` 传该页 `path` 取到参数明细，然后 `call_read_api` 逐页取数，最后在对话里用 Markdown 表格汇总。',
  ]
}

function sphereWorkingRules(): string[] {
  return [
    '- **全屏里没有「页面上下文」这条捷径**：`get_page_context` 只会告诉你自己在对话页，拿不到业务接口与参数。取数走 `search_pages`（按功能检索页面，拿到各页接口）或 `search_api` 找接口 → `call_read_api` 取数；参数名以返回的 `params` 为准，**不要凭印象猜**（例如把 `id` 写成 `uid`，后端会直接拒掉）。',
    '- **全屏里没有「当前页面表格」可操作**：不要试图更新页面搜索参数（这个工具在这里不给你）。用户要筛选/排序/翻页时，把条件转成**接口查询参数**取数，在对话里给出结果；如果用户就是想在表格里手动翻，用 `navigate_to` 提议去对应页面。涉及相对时间先用 `get_current_time` 换算。',
    '- **用户要求新建 / 创建 / 修改 / 编辑数据时**：这类多步表单操作**引导用户去页面完成**（全屏里没有表单工具）：先用 `list_navigation` 找到对应页面，用 `navigate_to` 提议过去。**不要**用 `call_write_api` 代替表单写库。',
    '- **删除 / 批量变更等写操作可以在全屏里直接做完**（不需要去页面）：先用接口查清对象、拿到 id（`search_pages`/`search_api` → `call_read_api`），再写。**批量操作（含批量删除、批量改状态）不要循环逐条调用** —— 用 `manage_tasks` 一次编排整组步骤（每步 `action: { tool: "call_write_api", input: {...} }`），客户端会顺序执行完、一次确认、整批回传结果。若接口有批量端点则直接用它，没有就编排。系统会弹审批卡并标明不可撤销，用户拒绝就停下、不要重试。',
  ]
}

/**
 * L7 进行中的任务清单（**随本轮环境变**）：把当前会话最后一份 Todo 目录注进上下文。
 *
 * 为什么直接注入而不是让模型自己去翻历史：**历史里的工具结果会衰减**
 * （`toModelMessages` 只保留最近 3 轮完整结果），刷新页面后的续做场景里，
 * `manage_tasks` 那次调用的**返回**很可能已经只剩占位符了 —— 模型于是"看不见"清单，
 * 要么重复创建一份、要么从头再来。这里把清单作为**每轮重算的上下文**注入，绕开衰减。
 *
 * 事实由调用方传入（`PromptFacts.activeTasks`，前端从会话消息里提取）：
 * 本包读不到 store，那正是它能同时在 Worker 里跑的原因。
 *
 * 没有清单（或全部完成 / 取消）时返回 `null`：整层不出现，不占上下文。
 */
export function buildActiveTasksLayer({ activeTasks }: PromptFacts): string | null {
  const tasks = activeTasks
  if (!tasks || tasks.length === 0) return null

  const uncompleted = tasks.filter(
    (task) => task.status !== 'completed' && task.status !== 'cancelled',
  )
  if (uncompleted.length === 0) return null

  return [
    '# 当前会话进行中/未完成的任务清单（Todo List 目录）',
    `当前任务共 ${tasks.length} 项，已完成 ${tasks.filter((task) => task.status === 'completed').length} 项，待处理如下：`,
    ...tasks.map((task) => `  * [${task.status}] ${task.id}. ${task.title}`),
    '',
    '【续做与取消守则】',
    '- 用户输入「继续 / 恢复 / 搞定剩下的」时：必须直接沿用上述任务清单！',
    '  1. 先调用 manage_tasks 将第一项未完成的任务状态更新为 in_progress；',
    '  2. 随后执行其对应操作（多任务直接调用写接口连续提交入库，严禁循环打开表单）；',
    '  3. 完成后调用 manage_tasks 将该项标记为 completed，并继续推进下一项；',
    '  4. 【最后一条任务必须标记完成】：最后一项处理完后必须调用 manage_tasks 将其标记为 completed，确保任务清单 100% 结束，并在正文以 Markdown 表格记录所有明细信息；',
    '- 用户若明确要求「取消 / 不要了 / 停止任务」时：调用 manage_tasks 将尚未完成的任务项标记为 cancelled。',
    '- 严禁丢弃现有清单或重复从头创建已完成的项！',
  ].join('\n')
}
