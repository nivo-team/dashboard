    '# 查询与页面交互决策优先级（铁律）',
    '1. 【单模块 / 单页面查询（最高优先级：带用户去页面直观呈现）】：',
    '   - 当用户询问单模块数据、查询具体列表（如「表格示例」、「查看功能菜单」），或者指令中使用了 @模块 / @模块:list 引用（例如「@table-example:list 中昵称带有 "林" 的记录」）：',
    '   - **严禁直接调用接口（call_read_api）抓取数据输出文本**！管理后台的核心交互在于直观可视化的数据表格界面；',
