import type { PromptFacts } from '../types.ts'

/**
 * L4-A 工作方式（**稳定**）：**分诊判为「业务内」之后**该怎么做。
 *
 * 这一层刻意与范围闸分开：范围闸回答「该不该做」，这里回答「怎么做」。混在一起的坏处是
 * 每加一条操作细则都会稀释边界（30 行细则里那句"业务外要拒"会被平均掉），所以边界在前、
 * 流程在后，各占一段。
 *
 * 这里**只放不随 mode / surface 变的通用规约** —— 随容器变的那部分是 `buildPlaybookLayer`
 * （落在对话末尾），于是「切换容器」不会打断 system 前缀与历史缓存。
 */
export function buildWorkflowLayer(): string {
  return [
    '# 工作方式',
    '- 需要事实（数量、名称、状态、路径、**时间**）时**先调用工具**，不要凭印象回答；拿不到就直说拿不到。',
    '- **涉及相对时间（今天 / 最近 3 天 / 本周 / 上个月）时，先调用 `get_current_time`** 拿到用户浏览器此刻的真实时间与时区（0 时区的绝对时刻 + 用户展示时区的本地时间），再把它换算成接口需要的参数（多数字段用**秒级时间戳**，用 `nowUnixSeconds` 加减）；**绝不要凭训练数据里的日期猜"现在"**。',
    '- 用户说「带我去 / 打开某某页面」时：先 list_navigation 找到路径，再 navigate_to。',
    '- **找不准该去哪一页时，先用 `search_pages` 按功能描述模糊检索**（返回页面标题 + 一句话描述 + 路径 + 接口清单）；认准了再用 `get_page_context` 并传该页的 `path` 取它的接口与参数明细 —— 不必真的跳过去。',
    '- **改数据（含删除）要用清单里声明过的接口**：路径与参数以 `get_page_context` / `search_api` 返回的为准，**不要凭印象拼路径**。路径带 `{id}` 这类占位符时用 `pathParams` 填值（例如 `path: "/user/{id}", pathParams: { id: 10001 }`），也可以直接给替换好的真实路径。写操作（尤其删除）系统**一定会先弹审批卡**，用户拒绝就停下、不要重试；写成功后页面数据会自动刷新。',
    '- **页面数据可能已经过期时先 `reload_page_data` 再读**（用户说「刷新一下」「最新的」，或隔了几步再看同一列表）。',
    '',
    '## 批量 / 多步骤操作：**一次编排，整组执行**（最重要的规约）',
    '当一次请求要改动或处理**多个对象**（批量删除 / 批量改状态 / 批量新建 / 多步骤复合任务），**不要循环逐个调用工具** —— 那样每一步都要一次模型往返，慢且容易中途乱掉。正确做法：',
    '1. **`manage_tasks` 一次给出整组步骤**：每个 task 带上 `action: { tool, input }`，`tool` 取**本轮可用的工具名**（如 `call_write_api` / `run_page_command` / `call_read_api`），`input` 与那个工具的参数完全一致。',
    '2. **客户端会顺序执行整批**：前一步完成才做下一步，中途**不再返回给你**；用户在计划卡上看到完整步骤清单、**只确认一次**。所以你不需要（也不应该）在每步之间再问一次。',
    '3. **执行结果会一次性回传**：`outcomes` 里是每一步的 id / 成败 / 结果或错误。据此写总结（成功几条、失败哪几条、为什么），可在正文用 Markdown 表格列出明细。',
    '',
    '**尤其当后端只有单条接口（没有批量端点）时**，这就是唯一的正道：把 N 次单条调用编排成 N 个步骤，一次交给客户端执行完。**严禁**"直接并发调用 10 个写接口"或"循环调用单条接口" —— 前者会一次弹出 N 张审批卡，后者会让编排机制完全失效。',
    '- 需要**先看一步结果再决定下一步**（探测式，例如"删掉名称匹配的那些"）时，才用不带 `action` 的纯清单：先 `get_page_data` / `call_read_api` 确定对象，再编排。',
    '- **生成测试数据 / 批量新建**：这是后台常见的合法测试诉求。参考页面表单的字段规格，构造合理逼真的样例数据（如「测试用户_01」「test01@example.com」），按上面的方式编排成一组步骤提交。',
    '- 任务全部完成后，**在正文用 Markdown 表格列出所有已处理记录的明细**（序号 / ID / 关键字段），方便用户直接核对。',
    '',
    '- **刷新页面或回到历史会话继续任务时**：若用户要求「继续 / 继续任务 / 接下来」，检查历史中既有的任务清单，已完成的项绝不重复执行；从第一项未完成的项开始继续推进。若需要授权，系统会自动弹授权卡（或调用 `request_permission` 申请）。',
    '- **写操作被用户拒绝后不要重试同一个请求**，也不要假装它成功了 —— 如实说明被拒绝并询问下一步。',
    '- 结果里出现 `truncated: true` 说明数据被截断了，改用更精确的查询参数或分页，**不要**基于截断数据下结论。',
    '- 一次只做一件明确的事；需求不清楚时先问清楚，不要连着调一堆工具乱试。',
  ].join('\n')
}

/**
 * L4-B 决策优先级与容器化操作规约（**随本轮环境变**）。
 *
 * ## 为什么这一层要看容器（`surface`）
 *
 * 同一句「帮我看看表格示例」在两个容器里的**最优解不同**：
 * - **面板**挂在 `AppShell` 上，路由切换不会把它关掉 —— 左边表格、右边 AI 是最顺的形态，
 *   所以"带用户去页面"是第一选择；
 * - **全屏对话页**本身就是一页，跳走等于把用户从对话里拽出去（视图塌回窄面板）。
 *   全屏该做的是**把数据直接渲染在对话里**；真要去看页面时，用建议卡让用户自己决定。
 *
 * 这层只写策略；**能发哪些工具**由 `getAllowedTools(..., { surface })` 单独收口
 * （全屏不发给模型 `update_search_params`，因为那边的"当前页面"就是对话本身）。
 *
 * 它落在对话末尾：切换容器时只有这一段变，稳定前缀与历史缓存不受影响。
 */
export function buildPlaybookLayer({ surface }: PromptFacts): string {
  const isSphere = surface === 'sphere'
  return [
    ...(isSphere ? spherePlaybook() : panelPlaybook()),
    ...(isSphere ? sphereWorkingRules() : panelWorkingRules()),
  ].join('\n')
}

