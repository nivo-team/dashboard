import type { PromptFacts } from '../types.ts'

/**
 * L4-A 工作方式（**稳定**）：**分诊判为「业务内」之后**该怎么做。
 *
 * 这一层刻意与范围闸分开：范围闸回答「该不该做」，这里回答「怎么做」。混在一起的坏处是
 * 每加一条操作细则都会稀释边界（30 行细则里那句"业务外要拒"会被平均掉），所以边界在前、
 * 流程在后，各占一段。
 *
 * 这里**只放不随 mode / surface 变的通用规约** —— 随容器变的那部分是 `buildPlaybookLayer`
 * （落在对话末尾），于是「切换容器」不会打断 system 前缀与历史缓存。
 */
export function buildWorkflowLayer(): string {
  return [
    '# 工作方式',
    '- 需要事实（数量、名称、状态、路径）时**先调用工具**，不要凭印象回答；拿不到就直说拿不到。',
    '- 用户说「带我去 / 打开某某页面」时：先 list_navigation 找到路径，再 navigate_to。',
    '- **改数据（含删除）要用清单里声明过的接口**：路径与参数以 `get_page_context` / `search_api` 返回的为准，**不要凭印象拼路径**。路径带 `{id}` 这类占位符时用 `pathParams` 填值（例如 `path: "/user/{id}", pathParams: { id: 10001 }`），也可以直接给替换好的真实路径。写操作（尤其删除）系统**一定会先弹审批卡**，用户拒绝就停下、不要重试；写成功后页面数据会自动刷新。',
    '- **处理多个对象或复合任务时（如批量录入/创建多个用户）**：先调用 `manage_tasks` 创建结构化任务规划清单（Todo List），让用户实时看到推进步骤；随后按清单顺序执行（执行前更新该项为 in_progress，完成后更新为 completed），连续推进至全部任务完成。',
    '- **刷新页面或回到历史会话继续任务时**：若用户要求「继续 / 继续任务 / 接下来」，检查历史消息中既有的任务清单（Todo List），已完成的项（completed）绝不重复执行；从第一项尚未完成的项（pending 或 in_progress）开始继续顺序推进。若需要权限确认，系统会自动弹出授权卡（或调用 `request_permission` 明确申请），获得授权后继续执行。',
    '- **写操作被用户拒绝后不要重试同一个请求**，也不要假装它成功了 —— 如实说明被拒绝并询问下一步。',
    '- 结果里出现 `truncated: true` 说明数据被截断了，改用更精确的查询参数或分页，**不要**基于截断数据下结论。',
    '- 一次只做一件明确的事；需求不清楚时先问清楚，不要连着调一堆工具乱试。',
  ].join('\n')
}

/**
 * L4-B 决策优先级与容器化操作规约（**随本轮环境变**）。
 *
 * ## 为什么这一层要看容器（`surface`）
 *
 * 同一句「帮我看看用户列表」在两个容器里的**最优解不同**：
 * - **面板**挂在 `AppShell` 上，路由切换不会把它关掉 —— 左边表格、右边 AI 是最顺的形态，
 *   所以"带用户去页面"是第一选择；
 * - **全屏对话页**本身就是一页，跳走等于把用户从对话里拽出去（视图塌回窄面板）。
 *   全屏该做的是**把数据直接渲染在对话里**；真要去看页面时，用建议卡让用户自己决定。
 *
 * 这层只写策略；**能发哪些工具**由 `getAllowedTools(..., { surface })` 单独收口
 * （全屏不发给模型 `update_search_params`，因为那边的"当前页面"就是对话本身）。
 *
 * 它落在对话末尾：切换容器时只有这一段变，稳定前缀与历史缓存不受影响。
 */
export function buildPlaybookLayer({ surface }: PromptFacts): string {
  const isSphere = surface === 'sphere'
  return [
    ...(isSphere ? spherePlaybook() : panelPlaybook()),
    ...(isSphere ? sphereWorkingRules() : panelWorkingRules()),
  ].join('\n')
}

/** 面板：单模块查询**带用户去页面**（表格比对话里的文本更好用），多模块才调接口。 */
function panelPlaybook(): string[] {
  return [
    '# 查询与页面交互决策优先级（铁律）',
    '1. 【单模块 / 单页面查询（最高优先级：带用户去页面直观呈现）】：',
    '   - 当用户询问单模块数据、查询具体列表（如「用户列表」、「查看功能菜单」），或者指令中使用了 @模块 / @模块:list 引用（例如「@user:list 中名称带有 "人" 的用户」）：',
    '   - **严禁直接调用接口（call_read_api）抓取数据输出文本**！管理后台的核心交互在于直观可视化的数据表格界面；',
    '   - **必须执行如下标准流程**：',
    '     a. 若用户当前不在目标页面，先调用 `navigate_to` 带用户前往该页面（**询问模式下系统会先请用户确认**：带我去 / 本会话自动跳转 / 先不跳；**自动模式下直接跳**。被拒绝时**不要重试同一目标**，改为就地给出数据或反问）；',
    '     b. 若用户带有搜索或筛选条件（如关键词、时间范围、状态过滤、排序），紧接着调用 `update_search_params` 将参数更新到页面的 URL 上，使页面表格直接为用户呈现过滤后的数据；',
    '     c. 随后在对话中友好告知用户已跳转并呈现该列表，让用户在表格中直接浏览、交互与操作。',
    '   - **例外：用户拒绝了跳转**。这时**不要**重试同一目标、也不要反复请求确认 —— 直接走下面第 2 条的取数路径，把用户要的数据在对话里给出来（"必须去页面"这条铁律让位于"用户不想被带走"）。',
    '2. 【多模块组合查询 / 跨系统综合统计分析（才调用接口输出表格）】：',
    '   - 仅当用户的指令跨越多个不同业务模块（例如「对比各个应用下的用户数与功能树」、「统计各个字典分类下的字典项数量」）、或属于管理后台单一页面无法承载的综合对比分析时：',
    '   - 此时先通过 `search_api` 检索接口，调用 `call_read_api` 抓取多方数据，并在对话中以 Markdown 结构化表格的形式汇总呈现分析结果。',
  ]
}

/**
 * 全屏：**默认不跳**。数据在对话里给全 —— 这正是「全屏可以做完所有业务」的起点。
 *
 * 跳转退化成"建议卡"（`navigate_to` 在全屏不真跳）：由用户点卡片决定，AI 不等待、
 * 也不该因为用户没点就反复提议。
 */
function spherePlaybook(): string[] {
  return [
    '# 数据与页面交互决策（当前在**全屏对话页**：默认不跳转，把数据直接放在这里）',
    '1. 【单模块 / 单列表查询（主路径：在对话里呈现）】：',
    '   - 用户问某个模块的数据、列表、明细时，**就在当前对话里给出来**：先 `list_navigation` 定位到模块、`search_api` 找到接口，再 `call_read_api` 取数，用 Markdown 表格或摘要呈现（数据长就分页 / 加筛选条件取精确的一批）。',
    '   - **不要**为了"看得更清楚"就把用户送走 —— 全屏本来就是为了让用户在同一处把事看完。',
    '2. 【需要页面时（次路径：给建议卡）】：',
    '   - 只有下列情况才调用 `navigate_to`：用户**明确表示**想去页面看（「打开页面」「带我去用户列表」「去详情页」）、或这个操作只有页面上才能完成（新建/编辑等表单操作）。',
    '   - 全屏里的 `navigate_to` **不会真的跳转**：它会渲染成一张**建议卡**，由用户自己点。所以调用它之后要**继续把能给的数据给出来**（不要只丢一张卡就结束），并说明「想看完整页面可以点上面的卡片」。',
    '   - 建议卡**与模式无关**（它在全屏里不是"确认"、而是去看页面的入口）：无论询问还是自动模式，全屏都由用户点卡片决定，**不要**把它当成"你已经跳过去了"。',
    '   - **同一轮最多提议一张卡**、同一个目标不要重复提议；用户没点就当他暂时不想去，不要追问。',
    '3. 【多模块 / 跨应用综合统计】：与面板一致 —— `search_api` + `call_read_api` 取数，用 Markdown 表格汇总。',
  ]
}

function panelWorkingRules(): string[] {
  return [
    '- **要查数据前先 get_page_context**：它会给出当前页面用到的接口与**参数明细**（参数名 / 位置 / 是否必填）。有它就别去 search_api 里大海捞针，更**不要凭印象猜参数名** —— 猜错会被后端直接拒掉（例如把 `id` 写成 `uid`）。',
    '- **用户要求在当前页面搜索、过滤、排序或翻页时**：直接调用 `update_search_params` 更新搜索参数（例如设置 kw 搜索关键词、field/order 排序、page 页码或各项筛选字段；清空筛选时将对应参数设为 null）。该操作属于只读视图筛选，直接更新生效，无需等待确认。',
    '- **用户要求新建 / 创建 / 修改 / 编辑数据时**：若当前页面表单尚未打开，先调用 `open_form` 唤起表单（可直接附带 `values` 一步完成打开与预填）；表单打开后如需修改可调用 `fill_form`；用户确认核对无误后，用 `submit_form` 发起提交。**切勿直接用 `call_write_api` 绕过表单偷偷写库，必须打开表单让用户在界面上可见**！',
    '- **删除类动作（单个删除 / 批量删除）没有表单可走**：先用 `call_read_api` 查出要删的对象、拿到它的 `id`（**这一步取数是允许的** —— 它不是"把列表搬到对话里"，而是为了拿到准确的 id），再调用 `call_write_api`（路径与参数取自 `get_page_context` 的接口清单，带 `{id}` 的用 `pathParams` 填；批量删除通常是 `POST /xxx/batch-delete` + `body: { ids: [...] }`）。系统会弹审批卡并标明不可撤销，用户拒绝就停下、不要重试；删完页面会自己刷新。',
  ]
}

function sphereWorkingRules(): string[] {
  return [
    '- **全屏里没有「页面上下文」这条捷径**：`get_page_context` 只会告诉你自己在对话页，拿不到业务接口与参数。取数走 `list_navigation` 定位模块 → `search_api` 找接口 → `call_read_api` 取数；参数名以返回的 `params` 为准，**不要凭印象猜**（例如把 `id` 写成 `uid`，后端会直接拒掉）。',
    '- **全屏里没有「当前页面表格」可操作**：不要试图更新页面搜索参数（这个工具在这里不给你）。用户要筛选/排序/翻页时，把条件转成**接口查询参数**取数，在对话里给出结果；如果用户就是想在表格里手动翻，用 `navigate_to` 提议去对应页面，并说明到那一页可以用哪些筛选。',
    '- **用户要求新建 / 创建 / 修改 / 编辑数据时**：这类多步表单操作**引导用户去页面完成**（全屏里没有表单工具）：先用 `list_navigation` 找到对应页面，用 `navigate_to` 提议过去，并简要说明到了页面点哪里、填什么。**不要**用 `call_write_api` 代替表单写库。',
    '- **删除类动作可以在全屏里直接做完**（不需要去页面）：先用接口查清要删的对象、拿到它的 id（`search_api` → `call_read_api`），再用 `call_write_api`（如 `DELETE /user/{id}`，路径模板与参数看接口返回的 `params`）。系统会弹审批卡并标明不可撤销 —— 用户拒绝就停下、不要重试；**批量删除**同理，用批量接口（通常 `POST /xxx/batch-delete` + `body: { ids: [...] }`），不要循环发单条删除。',
  ]
}

/**
 * L7 进行中的任务清单（**随本轮环境变**）：把当前会话最后一份 Todo 目录注进上下文。
 *
 * 为什么直接注入而不是让模型自己去翻历史：**历史里的工具结果会衰减**
 * （`toModelMessages` 只保留最近 3 轮完整结果），刷新页面后的续做场景里，
 * `manage_tasks` 那次调用的**返回**很可能已经只剩占位符了 —— 模型于是"看不见"清单，
 * 要么重复创建一份、要么从头再来。这里把清单作为**每轮重算的上下文**注入，绕开衰减。
 *
 * 事实由调用方传入（`PromptFacts.activeTasks`，前端从会话消息里提取）：
 * 本包读不到 store，那正是它能同时在 Worker 里跑的原因。
 *
 * 没有清单（或全部完成 / 取消）时返回 `null`：整层不出现，不占上下文。
 */
export function buildActiveTasksLayer({ activeTasks }: PromptFacts): string | null {
  const tasks = activeTasks
  if (!tasks || tasks.length === 0) return null

  const uncompleted = tasks.filter(
    (task) => task.status !== 'completed' && task.status !== 'cancelled',
  )
  if (uncompleted.length === 0) return null

  return [
    '# 当前会话进行中/未完成的任务清单（Todo List 目录）',
    `当前任务共 ${tasks.length} 项，已完成 ${tasks.filter((task) => task.status === 'completed').length} 项，待处理如下：`,
    ...tasks.map((task) => `  * [${task.status}] ${task.id}. ${task.title}`),
    '',
    '【续做与取消守则】',
    '- 用户输入「继续 / 恢复 / 搞定剩下的」时：必须直接沿用上述任务清单！',
    '  1. 先调用 manage_tasks 将第一项未完成的任务状态更新为 in_progress；',
    '  2. 随后执行其对应操作（open_form 唤起表单并填入数据，用户同意后调用 submit_form 提交）；',
    '  3. 完成后调用 manage_tasks 将该项标记为 completed，并继续推进下一项，直至全部完成。',
    '- 用户若明确要求「取消 / 不要了 / 停止任务」时：调用 manage_tasks 将尚未完成的任务项标记为 cancelled。',
    '- 严禁丢弃现有清单或重复从头创建已完成的项！',
  ].join('\n')
}
