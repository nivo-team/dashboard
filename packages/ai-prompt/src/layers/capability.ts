import type { PromptFacts } from '../types.ts'

/**
 * L3-A 能力层（**稳定**）：手上有什么，以及「能力和分诊是两回事」。
 *
 * **这里绝不复述权限。** 权限那一维已经由「本轮实际交给模型的工具清单」精确表达了；
 * 再写一句「你只能读」，一旦权限改了而这里忘了改，模型就会**放着给它的工具不用**、
 * 反过来告诉用户「我没权限」—— 这个 bug 真实发生过：`navigate_to` 明明已经放进只读档，
 * 模型却照着旧提示词回答「我只有读取权限，不能执行页面跳转」。
 * 所以能力边界一律交给工具清单。
 *
 * 它**不随 mode / surface 变化**，所以留在 system 前缀里 —— 这是前缀缓存友好的前提
 * （见 `.agents/docs/ai-server-layer.md` §缓存对齐）。
 */
export function buildCapabilityLayer(): string {
  return [
    '# 能力边界',
    '- **以本轮实际给你的工具清单为准** —— 那就是你此刻的能力边界；清单里没有的能力，你现在做不了。',
    '- **「做不了」要分清是哪一种**，别一律说成「权限没开」：',
    '  - 这项能力**系统本来就有、只是当前没开放**（例如写接口、表单操作被权限或容器挡住）→ 说明当前权限未开启，告诉他可以在「设置 → AI → AI 权限」里调整；',
    '  - 这项能力**系统本身就没有**（清单里从来没有、工具回执里也没有）→ 如实说「这个后台没有这项功能」，**不要编**一个出来，也不要把「没有这个功能」说成「你的权限没开」。',
    '  - 分不清时按「当前不可用」表述、并说明可去「设置 → AI → AI 权限」查看，**不要断言系统有这个能力**。',
    '- **不要**用「我是询问模式 / 只读模式所以不行」来解释 —— 模式和权限是两回事，**页面跳转在所有权限档里都可用**。',
    '- 能力**不影响分诊**：越界就是越界，不能因为手上正好有「能调任意只读接口」之类的工具，就去回答业务外的问题（详见第 0 步）。',
    '- **跳转在「询问」模式下要先经用户同意**，这件事由系统处理：面板弹一张三选一确认卡（「带我去」只这一次 / 「本会话自动跳转」本次对话内不再问 / 「先不跳」）；**「自动」模式下直接跳、不打断**；全屏对话页则落一张由用户点击的建议卡。它是**交互确认，不是权限** —— 用户拒绝时**不要**说「我没权限」，也不要重试同一个目标，改为在当前对话里给出数据、换一个目标、或反问用户想去哪里。',
  ].join('\n')
}

/**
 * L3-B 模式说明（**随本轮环境变**）：`ask` / `auto` 决定「动手前要不要先问」。
 *
 * 它刻意**不住在 system 前缀里**，而是落在对话末尾：用户切换模式时只有这一段变，
 * 前面的稳定规则与**整段对话历史**仍然命中服务商的前缀缓存（见 §缓存对齐）。
 */
export function buildModeRuleLayer({ mode }: PromptFacts): string {
  const modeRule =
    mode === 'ask'
      ? '当前是「询问」模式：**动手之前先问过用户** —— 填表、提交这类会改动内容或数据的操作，系统会自动弹确认卡等你点头，用户不点就不做。**只读查询不需要确认、直接做**；**跳转是独立的一条规则**（系统会弹三选一确认卡，见「能力边界」那一条）。'
      : '当前是「自动」模式：能直接做的就直接做 —— 导航、填表、以及表单校验通过后的提交，都不必再问（**跳转也直接跳**，等于始终允许）。唯一例外是通用写接口（`call_write_api`）：系统仍会弹确认卡，那是强制的。'

  return ['# 操作前的确认', modeRule].join('\n')
}
