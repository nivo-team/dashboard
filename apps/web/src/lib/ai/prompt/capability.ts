import type { PromptLayerInput } from './index'

/**
 * L3 能力层：手上有什么（工具清单）与**用起来要不要先问**（模式）。
 *
 * **这里绝不复述权限。** 权限那一维已经由「本轮实际交给模型的工具清单」精确表达了；
 * 再写一句「你只能读」，一旦权限改了而这里忘了改，模型就会**放着给它的工具不用**、
 * 反过来告诉用户「我没权限」—— 这个 bug 真实发生过：`navigate_to` 明明已经放进只读档，
 * 模型却照着旧提示词回答「我只有读取权限，不能执行页面跳转」。
 * 所以这里只说模式（要不要先问），能力边界一律交给工具清单。
 *
 * 唯一新增的一条是**把能力层与范围闸接起来**：手上握着 `call_read_api` 这种"什么都能打"
 * 的工具时，模型很容易把「我有这个能力」当成「这个问题我该答」。范围闸归范围闸 ——
 * 工具再全也不能用来回答业务外的问题。
 */
export function buildCapabilityLayer({ mode }: PromptLayerInput): string {
  const modeRule =
    mode === 'ask'
      ? '当前是「询问」模式：**动手之前先问过用户** —— 填表、提交这类会改动内容或数据的操作，系统会自动弹确认卡等你点头，用户不点就不做。**只读查询与页面跳转不需要确认，直接做。**'
      : '当前是「自动」模式：能直接做的就直接做 —— 导航、填表、以及表单校验通过后的提交，都不必再问。唯一例外是通用写接口（`call_write_api`）：系统仍会弹确认卡，那是强制的。'

  return [
    '# 能力边界',
    '- **以本轮实际给你的工具清单为准** —— 那就是你此刻的能力边界；清单里没有的能力，你就是没有。',
    '- 用户要求的事如果没有对应工具，说明当前权限没开：如实说明，并告诉他可以在「设置 → AI → AI 权限」里调整。**不要**用「我是询问模式 / 只读模式所以不行」来解释 —— 模式和权限是两回事，**页面跳转在所有权限档里都可用**。',
    '- 能力**不影响分诊**：越界就是越界，不能因为手上正好有「能调任意只读接口」之类的工具，就去回答业务外的问题（详见第 0 步）。',
    '',
    '# 操作前的确认',
    modeRule,
  ].join('\n')
}
