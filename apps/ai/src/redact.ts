/**
 * 出站脱敏 —— **预留落点，本轮不生效**。
 *
 * 为什么现在就把文件建起来：脱敏必须挂在「内容离开我们的信任边界之前」这一处，
 * 而不是散在各个调用点。本轮 Hono 只拼提示词（内容还没出站），所以这里的默认实现是
 * **原样返回**；等模型流量切到本服务时，只改这一个函数即可，调用点一处都不用动。
 *
 * ## 下一轮要做的三件事（顺序别反）
 *
 * 1. **定义规则**：手机号 / 邮箱 / 身份证 / 银行卡这类**格式可识别**的，用正则替换；
 *    真正的企业敏感字段（客户名、订单号…）格式上无法识别，只能靠**字段名黑名单** +
 *    调用方在 `PromptFacts` 里少给 —— 提示词服务看不到数据库，猜不出哪些是敏感字段。
 * 2. **决定策略**：是「替换成占位符」（模型仍能推理结构）还是「整条拦截」（更强但会
 *    让模型答非所问）。两者可以按规则分级。
 * 3. **接 Cloudflare AI Gateway 的 DLP 作为第二道**：它作用在真正的出站路径上，
 *    即使本函数漏了规则也还有一层（免费，见文档的「脱敏」一节）。
 *
 * ## 为什么不能只依赖网关侧 DLP
 *
 * 网关只能看到「已经发出去的内容」；本函数在**进程内**，可以顺手把命中项写进审计日志、
 * 或按用户 / 应用做更细的策略。两层是互补关系，不是二选一。
 */

export interface RedactResult {
  /** 脱敏后的文本（本轮与输入相同） */
  text: string
  /** 命中并被替换的处数（本轮恒为 0） */
  redacted: number
  /** 命中的规则名（本轮为空；接规则后用于审计） */
  rules: string[]
}

/** 本轮：空实现。接规则前不要把它当"已脱敏"。 */
export function redactOutbound(text: string): RedactResult {
  return { text, redacted: 0, rules: [] }
}

/** 当前是否真的会改写内容 —— 供 `/health` 自述，避免把「占位」误读成「已防护」。 */
export const REDACTION_ENABLED = false
